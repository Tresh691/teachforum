    <h1>Политика конфиденциальности</h1>
    <p><strong>Дата последнего обновления:</strong> 24.06.2026</p>
    
    <h2>1. Общие положения</h2>
    <p>
        Настоящая Политика конфиденциальности определяет, как TeachForum (далее — «Сервис») собирает, использует и защищает персональные данные пользователей (учителей и учеников).
        Используя Сервис, вы соглашаетесь с условиями данной Политики.
    </p>
    
    <h2>2. Какие данные мы собираем</h2>
    <ul>
        <li><strong>Учителя:</strong> логин, адрес электронной почты, пароль (в зашифрованном виде), тарифный план, аватар (по желанию).</li>
        <li><strong>Ученики:</strong> имя, фамилия, логин, пароль (в зашифрованном виде), аватар (по желанию). Ученики добавляются учителем, и их данные используются только в рамках учебного процесса.</li>
        <li><strong>Технические данные:</strong> IP-адрес, тип браузера, файлы cookie для авторизации.</li>
    </ul>
    
    <h2>3. Как мы используем данные</h2>
    <ul>
        <li>Обеспечение работы личного кабинета преподавателя и ученика.</li>
        <li>Отправка уведомлений о регистрации, восстановлении пароля, назначении заданий (при настроенных email).</li>
        <li>Улучшение качества сервиса.</li>
    </ul>
    
    <h2>4. Хранение и защита данных</h2>
    <p>
        Данные хранятся на защищённых серверах. Пароли хешируются современными алгоритмами.
        Мы не передаём персональные данные третьим лицам, за исключением случаев, предусмотренных законодательством РФ.
    </p>
    
    <h2>5. Файлы cookie</h2>
    <p>
        Сервис использует файлы cookie для запоминания авторизованного пользователя (опция «Запомнить меня»).
        Вы можете отключить cookie в настройках браузера, но это может ограничить функциональность.
    </p>
    
    <h2>6. Ваши права</h2>
    <p>
        Вы можете в любой момент запросить удаление своих данных, обратившись в поддержку.
        Ученики могут обратиться к своему преподавателю для удаления профиля.
    </p>
    
