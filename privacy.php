    <h1>Политика конфиденциальности</h1>
    <p><strong>Дата последнего обновления:</strong> 02.09.2026</p>

    <h2>1. Общие положения</h2>
    <p>
        1.1. Настоящая Политика конфиденциальности (далее — «Политика») определяет порядок обработки и защиты персональных данных пользователей платформы TeachForum (далее — «Сервис»).
    </p>
    <p>
        1.2. Используя Сервис, вы даёте согласие на обработку своих персональных данных в соответствии с настоящей Политикой и Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных».
    </p>
    <p>
        1.3. В случае несогласия с условиями Политики вы должны прекратить использование Сервиса.
    </p>

    <h2>2. Какие данные мы собираем</h2>
    <p>2.1. Данные учителей:</p>
    <ul>
        <li>логин, адрес электронной почты, пароль (в зашифрованном виде);</li>
        <li>тарифный план, срок действия доступа;</li>
        <li>аватар, настройки бокового меню, часовой пояс.</li>
    </ul>
    <p>2.2. Данные учеников:</p>
    <ul>
        <li>имя, фамилия, логин, пароль (в зашифрованном виде);</li>
        <li>аватар, часовой пояс;</li>
        <li>ставка за урок (устанавливается учителем).</li>
    </ul>
    <p>2.3. Данные об учебном процессе:</p>
    <ul>
        <li>расписание уроков: дата, время, тема, комментарий, статус оплаты;</li>
        <li>групповые уроки: состав участников, индивидуальные статусы оплаты;</li>
        <li>домашние задания: названия, тексты, ссылки, статусы выполнения, категории, блоки;</li>
        <li>библиотека заданий: разделы, блоки, задания, ссылки;</li>
        <li>лекции и шпоры: блоки, материалы, комментарии, файлы;</li>
        <li>пробники: название, предмет, дата, баллы, комментарий.</li>
    </ul>
    <p>2.4. Файлы:</p>
    <ul>
        <li>загруженные учителем материалы, прикреплённые к урокам, лекциям, шпорам, кастомным разделам и пробникам.</li>
    </ul>
    <p>2.5. Технические данные:</p>
    <ul>
        <li>IP-адрес, тип браузера, файлы cookie, журналы ошибок, данные о соединении.</li>
    </ul>

    <h2>3. Цели обработки персональных данных</h2>
    <ul>
        <li>предоставление доступа к личному кабинету учителя и ученика;</li>
        <li>ведение расписания и учёт оплат;</li>
        <li>формирование статистики по оплатам и пробникам;</li>
        <li>хранение и отображение учебных материалов;</li>
        <li>отправка уведомлений о регистрации, восстановлении пароля, назначении заданий (при наличии email);</li>
        <li>улучшение качества работы Сервиса.</li>
    </ul>

    <h2>4. Правовые основания обработки</h2>
    <p>
        4.1. Обработка персональных данных осуществляется на основании:
    </p>
    <ul>
        <li>согласия пользователя на обработку его данных;</li>
        <li>необходимости исполнения договора об оказании услуг (для учителей);</li>
        <li>требований законодательства Российской Федерации.</li>
    </ul>
    <p>
        4.2. Согласие на обработку персональных данных даётся при регистрации и подтверждается использованием Сервиса.
    </p>

    <h2>5. Условия обработки и передачи третьим лицам</h2>
    <p>
        5.1. Сервис не передаёт персональные данные третьим лицам, за исключением случаев:
    </p>
    <ul>
        <li>наличие согласия пользователя;</li>
        <li>необходимость привлечения хостинг-провайдера или иных технических партнёров для обеспечения работы Сервиса;</li>
        <li>предусмотренных законодательством РФ.</li>
    </ul>
    <p>
        5.2. Хостинг-провайдер может обрабатывать данные по поручению Сервиса исключительно для технического обеспечения.
    </p>

    <h2>6. Хранение и защита данных</h2>
    <p>
        6.1. Персональные данные хранятся на защищённых серверах. Пароли хешируются современными алгоритмами.
    </p>
    <p>
        6.2. Принимаются необходимые организационные и технические меры для защиты данных от неправомерного доступа, изменения, раскрытия или уничтожения.
    </p>

    <h2>7. Сроки хранения</h2>
    <p>
        7.1. Данные обрабатываются до момента удаления аккаунта или отзыва согласия.
    </p>
    <p>
        7.2. Некоторые данные (например, журналы ошибок) могут храниться в течение ограниченного срока, необходимого для технической диагностики.
    </p>

    <h2>8. Права субъектов персональных данных</h2>
    <p>
        8.1. Пользователь вправе:
    </p>
    <ul>
        <li>запрашивать информацию об обработке своих данных;</li>
        <li>требовать уточнения, блокирования или уничтожения данных;</li>
        <li>отозвать согласие на обработку персональных данных;</li>
        <li>обратиться в службу поддержки для удаления аккаунта и связанных данных.</li>
    </ul>
    <p>
        8.2. Ученик может обратиться к своему преподавателю для удаления профиля и связанных данных.
    </p>

    <h2>9. Файлы cookie и аналитика</h2>
    <p>
        9.1. Сервис использует файлы cookie для запоминания авторизованного пользователя (опция «Запомнить меня»), а также для корректной работы интерфейса.
    </p>
    <p>
        9.2. Пользователь может отключить cookie в настройках браузера, но это может ограничить функциональность Сервиса.
    </p>

    <h2>10. Персональные данные несовершеннолетних</h2>
    <p>
        10.1. Сервис предназначен для использования учителями и их учениками. Ученики могут быть несовершеннолетними. Учитель, добавляя ученика, гарантирует, что получил согласие законного представителя на обработку данных ученика, либо действует в рамках образовательного процесса.
    </p>
    <p>
        10.2. Если выявляется факт обработки данных несовершеннолетнего без согласия законного представителя, Сервис вправе удалить такие данные.
    </p>

    <h2>11. Заключительные положения</h2>
    <p>
        11.1. Сервис вправе вносить изменения в настоящую Политику. Новая редакция вступает в силу с момента её публикации на сайте.
    </p>
    <p>
        11.2. Продолжение использования Сервиса после изменения Политики означает согласие с новой редакцией.
    </p>

